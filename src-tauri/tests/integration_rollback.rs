//! Integration tests for the rollback / snapshot engine.
//!
//! These tests exercise the real public API from `iptv_hub_core::rollback`:
//! `create_archive`, `restore_archive`, `sweep_expired`, `begin_swap`,
//! `SwapGuard::commit`, and `recover_orphan_swaps`. Per CONTRACT.md §2.2, no
//! mocks — every test stands up a real on-disk tree under `tempfile::TempDir`,
//! drives the public functions, and asserts byte-level outcomes.

#![allow(
    clippy::missing_panics_doc,
    clippy::missing_errors_doc,
    clippy::uninlined_format_args
)]

use std::fs;
use std::path::{Path, PathBuf};
use std::time::{Duration, SystemTime};

use iptv_hub_core::paths::AppPaths;
use iptv_hub_core::rollback::{
    begin_swap, create_archive, recover_orphan_swaps, restore_archive, sweep_expired,
};
use sha2::{Digest as _, Sha256};
use tempfile::TempDir;

// ── helpers ──────────────────────────────────────────────────────────────────────

async fn make_paths(root: &Path) -> AppPaths {
    let paths = AppPaths::for_tests(root);
    paths.ensure_exist().await.expect("ensure_exist");
    paths
}

fn sha256_file(path: &Path) -> String {
    let bytes = fs::read(path).unwrap_or_else(|e| panic!("read {}: {}", path.display(), e));
    let mut hasher = Sha256::new();
    hasher.update(&bytes);
    hex::encode(hasher.finalize())
}

fn write_file(path: &Path, contents: &[u8]) {
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).unwrap_or_else(|e| panic!("mkdir {}: {}", parent.display(), e));
    }
    fs::write(path, contents).unwrap_or_else(|e| panic!("write {}: {}", path.display(), e));
}

// ── tests ────────────────────────────────────────────────────────────────────────

/// Snapshot a tree containing a symlink, restore, and assert the symlink survives.
///
/// On Windows, creating a file symlink without admin/developer-mode privileges
/// fails with `ERROR_PRIVILEGE_NOT_HELD` (1314). In that case we emit a clear
/// skip notice and return successfully — the contract permits skipping with a
/// visible message, not silent disabling.
#[tokio::test]
async fn snapshot_restore_symlinks() {
    let tmp = TempDir::new().expect("tempdir");
    let source_dir = tmp.path().join("source");
    let target_file = source_dir.join("real.txt");
    let link_path = source_dir.join("link.txt");

    fs::create_dir_all(&source_dir).expect("mkdir source");
    fs::write(&target_file, b"hello-from-target").expect("write target");

    #[cfg(unix)]
    {
        std::os::unix::fs::symlink("real.txt", &link_path).expect("symlink");
    }
    #[cfg(windows)]
    {
        if let Err(e) = std::os::windows::fs::symlink_file("real.txt", &link_path) {
            eprintln!(
                "\nsnapshot_restore_symlinks: SKIPPING — cannot create symlink on this Windows host \
                 (need admin or Developer Mode). os error: {}",
                e
            );
            return;
        }
    }

    let cache_root = tmp.path().join("cache");
    fs::create_dir_all(&cache_root).expect("mkdir cache");

    let snap = create_archive("symlink-app", "v1", &source_dir, &cache_root)
        .await
        .expect("create_archive");
    assert!(snap.path.exists(), "archive file should exist");

    // Delete the entire source tree.
    fs::remove_dir_all(&source_dir).expect("remove source");
    assert!(!source_dir.exists());

    restore_archive(&snap.path, &source_dir)
        .await
        .expect("restore_archive");

    // The real file must be back, byte-identical.
    let real_after = fs::read(source_dir.join("real.txt")).expect("read real after restore");
    assert_eq!(real_after, b"hello-from-target");

    // The symlink must be back, pointing at "real.txt".
    let meta = fs::symlink_metadata(&link_path).expect("symlink metadata");
    assert!(
        meta.file_type().is_symlink(),
        "link.txt should be a symlink after restore (was {:?})",
        meta.file_type()
    );
    let resolved = fs::read_link(&link_path).expect("read_link");
    assert_eq!(
        resolved,
        PathBuf::from("real.txt"),
        "symlink target should be preserved"
    );
}

/// Snapshot a 5 MiB binary file with deterministic-but-non-trivial content,
/// restore, and assert byte-for-byte equality via SHA-256.
#[tokio::test]
async fn snapshot_restore_large_binary() {
    let tmp = TempDir::new().expect("tempdir");
    let source_dir = tmp.path().join("source");
    let big_path = source_dir.join("payload.bin");

    fs::create_dir_all(&source_dir).expect("mkdir source");

    // 5 MiB of pseudo-random-looking bytes generated by a tiny LCG. We avoid the
    // `rand` crate because adding a dev-dep is out of scope for this slice.
    let mut buf = vec![0u8; 5 * 1024 * 1024];
    let mut state: u64 = 0x_C0FF_EE12_3456_789A;
    for chunk in buf.chunks_mut(8) {
        state = state
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1);
        let bytes = state.to_le_bytes();
        for (i, b) in chunk.iter_mut().enumerate() {
            *b = bytes[i];
        }
    }
    fs::write(&big_path, &buf).expect("write big file");
    let expected_sha = sha256_file(&big_path);

    let cache_root = tmp.path().join("cache");
    fs::create_dir_all(&cache_root).expect("mkdir cache");
    let snap = create_archive("big-app", "v1", &source_dir, &cache_root)
        .await
        .expect("create_archive");
    assert!(snap.size_bytes > 0);
    // tar.zst of a 5 MiB random blob should be at most ~5.1 MiB; sanity check
    // that compression didn't explode catastrophically.
    assert!(
        snap.size_bytes < 8 * 1024 * 1024,
        "tar.zst of 5MiB random data was {} bytes, suspiciously large",
        snap.size_bytes
    );

    fs::remove_dir_all(&source_dir).expect("remove source");
    restore_archive(&snap.path, &source_dir)
        .await
        .expect("restore_archive");

    let actual_sha = sha256_file(&big_path);
    assert_eq!(
        actual_sha, expected_sha,
        "restored payload must be byte-identical to original"
    );
}

/// Snapshot a tree containing two empty directories, restore, and assert that
/// the empty dirs are recreated. `tar` only preserves empty directories when
/// they are appended explicitly — `create_archive` does so via `WalkDir`.
#[tokio::test]
async fn snapshot_restore_empty_dirs() {
    let tmp = TempDir::new().expect("tempdir");
    let source_dir = tmp.path().join("source");
    let empty1 = source_dir.join("dir").join("empty1");
    let empty2 = source_dir.join("dir").join("empty2");
    let real_file = source_dir.join("dir").join("file.txt");

    fs::create_dir_all(&empty1).expect("mkdir empty1");
    fs::create_dir_all(&empty2).expect("mkdir empty2");
    write_file(&real_file, b"non-empty sibling");

    let cache_root = tmp.path().join("cache");
    fs::create_dir_all(&cache_root).expect("mkdir cache");
    let snap = create_archive("empty-dirs-app", "v1", &source_dir, &cache_root)
        .await
        .expect("create_archive");

    fs::remove_dir_all(&source_dir).expect("remove source");
    restore_archive(&snap.path, &source_dir)
        .await
        .expect("restore_archive");

    assert!(
        empty1.is_dir(),
        "empty1 should exist as a directory after restore"
    );
    assert!(
        empty2.is_dir(),
        "empty2 should exist as a directory after restore"
    );
    assert_eq!(fs::read_dir(&empty1).expect("read empty1").count(), 0);
    assert_eq!(fs::read_dir(&empty2).expect("read empty2").count(), 0);
    assert!(real_file.exists(), "sibling file should also be restored");
}

/// Place three "snapshot" files under `<root>/rollback/<app>/`, age one of them
/// to 8 days ago using `File::set_modified`, run `sweep_expired(7)`, and assert
/// exactly one file was deleted.
#[tokio::test]
async fn expiry_sweep_deletes_old_snapshots() {
    let tmp = TempDir::new().expect("tempdir");
    let rollback_root = tmp.path().join("rollback");
    let app_dir = rollback_root.join("an-app");
    fs::create_dir_all(&app_dir).expect("mkdir app dir");

    let fresh = app_dir.join("fresh.tar.zst");
    let recent = app_dir.join("recent.tar.zst");
    let old = app_dir.join("old.tar.zst");
    for p in [&fresh, &recent, &old] {
        fs::write(p, b"snapshot bytes").unwrap_or_else(|e| panic!("write {}: {}", p.display(), e));
    }

    // Set the "old" file's mtime to 8 days ago.
    let eight_days_ago = SystemTime::now()
        .checked_sub(Duration::from_secs(8 * 86_400))
        .expect("now - 8d");
    {
        let f = fs::OpenOptions::new()
            .write(true)
            .open(&old)
            .expect("open old");
        f.set_modified(eight_days_ago).expect("set_modified on old");
    }

    let deleted = sweep_expired(&rollback_root, 7)
        .await
        .expect("sweep_expired");
    assert_eq!(deleted, 1, "exactly one snapshot should be expired");
    assert!(!old.exists(), "old.tar.zst should have been deleted");
    assert!(fresh.exists(), "fresh.tar.zst must still exist");
    assert!(recent.exists(), "recent.tar.zst must still exist");
}


/// `begin_swap` writes a marker. After `commit()` the marker file must be gone.
#[tokio::test]
async fn swap_guard_commit_removes_marker() {
    let tmp = TempDir::new().expect("tempdir");
    let paths = make_paths(tmp.path()).await;

    // The "snapshot" and "target" don't matter for this test — commit doesn't
    // touch them. But provide real paths so the marker JSON is valid.
    let snapshot = tmp.path().join("apps").join("cache").join("dummy.tar.zst");
    fs::write(&snapshot, b"not used in this test").expect("write dummy");
    let target = tmp
        .path()
        .join("apps")
        .join("upstream")
        .join("dummy-target");

    let guard = begin_swap("commit-test", &paths, &snapshot, &target).expect("begin_swap");
    let marker_path = guard.marker_path().to_path_buf();
    assert!(
        marker_path.exists(),
        "marker should be on disk after begin_swap"
    );

    guard.commit().expect("commit");
    assert!(
        !marker_path.exists(),
        "marker file should be removed by commit()"
    );
}

/// Drop a `SwapGuard` without committing, then call `recover_orphan_swaps`. It
/// must find the orphan marker, restore from the recorded snapshot, and remove
/// the marker.
#[tokio::test]
async fn crash_recovery_restores_when_marker_present() {
    let tmp = TempDir::new().expect("tempdir");
    let paths = make_paths(tmp.path()).await;

    // Build a real "before" tree, snapshot it, then mutate the tree to simulate
    // a half-finished swap that was killed mid-way.
    let install_dir = tmp.path().join("apps").join("upstream").join("an-app");
    fs::create_dir_all(&install_dir).expect("mkdir install");
    fs::write(install_dir.join("hello.txt"), b"BEFORE").expect("write before");

    let cache_root = tmp.path().join("apps").join("cache");
    let snap = create_archive("recover-app", "v1", &install_dir, &cache_root)
        .await
        .expect("create_archive");

    // Begin the swap, then "crash" by overwriting the target with bogus content
    // and dropping the guard without commit().
    {
        let _guard =
            begin_swap("recover-app", &paths, &snap.path, &install_dir).expect("begin_swap");
        fs::write(install_dir.join("hello.txt"), b"AFTER-but-crashed").expect("write after");
        // Add a stray file that should disappear after recovery.
        fs::write(install_dir.join("partial-extract.tmp"), b"junk").expect("write junk");
        // Guard drops here without commit — marker stays on disk.
    }

    let marker_path = paths
        .apps_root()
        .join("cache")
        .join("rollback")
        .join("recover-app.swap.marker");
    assert!(marker_path.exists(), "marker should be left on disk");

    let recovered = recover_orphan_swaps(&paths)
        .await
        .expect("recover_orphan_swaps");
    assert_eq!(recovered, vec!["recover-app".to_string()]);

    // Restored content must be the BEFORE content.
    let restored = fs::read(install_dir.join("hello.txt")).expect("read restored");
    assert_eq!(
        restored, b"BEFORE",
        "rollback should restore original content"
    );
    // Stray file from the half-finished swap must be gone — `restore_archive`
    // wipes the target before extracting.
    assert!(
        !install_dir.join("partial-extract.tmp").exists(),
        "stray half-extracted file must be cleared by restore"
    );
    // Marker must be removed by recovery.
    assert!(
        !marker_path.exists(),
        "marker should be removed after successful recovery"
    );
}

/// `recover_orphan_swaps` against an empty rollback dir is a no-op.
#[tokio::test]
async fn recovery_with_no_markers_is_noop() {
    let tmp = TempDir::new().expect("tempdir");
    let paths = make_paths(tmp.path()).await;

    let recovered = recover_orphan_swaps(&paths)
        .await
        .expect("recover_orphan_swaps");
    assert!(
        recovered.is_empty(),
        "no markers → empty recovery list, got {:?}",
        recovered
    );
}

/// A corrupt marker is quarantined (renamed to `*.corrupt`) rather than
/// deleted; the recovery function must not panic.
#[tokio::test]
async fn corrupt_marker_is_quarantined() {
    let tmp = TempDir::new().expect("tempdir");
    let paths = make_paths(tmp.path()).await;

    let rollback_dir = paths.apps_root().join("cache").join("rollback");
    fs::create_dir_all(&rollback_dir).expect("mkdir rollback");
    let corrupt_marker = rollback_dir.join("corrupt-app.swap.marker");
    fs::write(&corrupt_marker, b"{ this is not valid json").expect("write corrupt marker");

    let recovered = recover_orphan_swaps(&paths)
        .await
        .expect("recover_orphan_swaps");
    assert!(
        recovered.is_empty(),
        "corrupt marker should not appear in recovered list"
    );
    assert!(
        !corrupt_marker.exists(),
        "original corrupt marker should be renamed"
    );
    let quarantine = rollback_dir.join("corrupt-app.swap.marker.corrupt");
    assert!(
        quarantine.exists(),
        "quarantined marker should exist at {}",
        quarantine.display()
    );
}
